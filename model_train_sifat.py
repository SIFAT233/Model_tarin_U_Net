def calculate_metrics(logits, masks):

    probabilities = torch.sigmoid(logits)

    predictions = (probabilities > 0.5).float()

    predictions = predictions.view(
        predictions.size(0), -1
    )

    masks = masks.view(
        masks.size(0), -1
    )

    intersection = (
        predictions * masks
    ).sum(dim=1)

    union = (
        predictions + masks
    ).sum(dim=1)

    dice = (
        2 * intersection + 1e-7
    ) / (
        union + 1e-7
    )

    iou = (
        intersection + 1e-7
    ) / (
        union - intersection + 1e-7
    )

    return dice.mean().item(), iou.mean().item()

